"""Generate the Lucide icon fonts (font_lucide_<px>.c) and icons.h from ui/icons.txt.

The source is the pinned Lucide webfont in tools/lucide/ (lucide-static, ISC licence: LICENSES/ISC-Lucide.txt).
Each listed icon becomes one glyph in every size; icons.h maps names to UTF-8 strings: play -> ICON_PLAY.

Usage: python3 tools/gen_lucide_icons.py [--converter path/to/lv_font_conv] [--sizes 16,20,24,28,32]
"""
import argparse, json, subprocess, sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
SRC = APP / 'tools' / 'lucide'
SIZES = (16, 20, 24, 28, 32)
DEFAULT_CONV = APP.parent.parent / 'tools' / 'icons' / 'node_modules' / '.bin' / 'lv_font_conv'


def utf8_literal(cp):
    return ''.join('\\x%02X' % b for b in chr(cp).encode('utf-8'))


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--converter', type=Path, default=DEFAULT_CONV)
    p.add_argument('--sizes', default=','.join(map(str, SIZES)))
    a = p.parse_args()
    sizes = [int(s) for s in a.sizes.split(',')]

    codepoints = json.loads((SRC / 'codepoints.json').read_text())
    names = [l.strip() for l in (APP / 'icons.txt').read_text().splitlines() if l.strip() and not l.startswith('#')]
    missing = [n for n in names if n not in codepoints]
    if missing:
        sys.exit('unknown Lucide icon(s): ' + ', '.join(missing) + '  (see lucide.dev for names)')
    if len(set(names)) != len(names):
        sys.exit('duplicate names in icons.txt')

    rng = ','.join('0x%X' % codepoints[n] for n in names)
    for px in sizes:
        out = APP / ('font_lucide_%d.c' % px)
        subprocess.run([str(a.converter), '--font', 'tools/lucide/lucide.ttf', '--range', rng, '--size', str(px),
                        '--bpp', '4', '--format', 'lvgl', '--no-compress', '--force-fast-kern-format',
                        '--lv-font-name', 'font_lucide_%d' % px, '-o', out.name], check=True, cwd=APP)
        body = out.read_text()
        hdr = ('/* SPDX-License-Identifier: ISC */\n'
               '/* Lucide icons (lucide-static %s), ISC licence: LICENSES/ISC-Lucide.txt. Generated by '
               'tools/gen_lucide_icons.py from icons.txt - do not edit. */\n') % (SRC / 'VERSION').read_text().split()[1]
        out.write_text(hdr + body)
        print('wrote', out.name)

    h = ['/* SPDX-License-Identifier: GPL-3.0-or-later */',
         '/* Lucide icon glyphs. Generated by tools/gen_lucide_icons.py from icons.txt - do not edit. */',
         '#pragma once', '#include "lvgl/lvgl.h"', '']
    h += ['LV_FONT_DECLARE(font_lucide_%d)' % px for px in sizes] + ['']
    w = max(len(n) for n in names) + 6
    h += ['#define %-*s "%s"' % (w, 'ICON_' + n.upper().replace('-', '_'), utf8_literal(codepoints[n])) for n in names]
    h += ['', '#define ICONS_COUNT %d' % len(names),
          '#define ICONS_ALL(X) \\'] + ['    X(%s, "%s") \\' % ('ICON_' + n.upper().replace('-', '_'), n) for n in names] + ['']
    (APP / 'icons.h').write_text('\n'.join(h) + '\n')
    print('wrote icons.h (%d icons x %d sizes)' % (len(names), len(sizes)))


if __name__ == '__main__':
    main()
